"""
evaluation.py

Evaluation system for assessing Q&A response quality.
Compares actual responses against expected responses using LLM-based evaluation.

Functionality:
- LLM-based response quality evaluation
- Comparison of actual vs expected responses
- Scoring system (0-100 scale) for response accuracy
- Detailed reasoning for score justification
- Batch evaluation of test datasets
- CSV output for evaluation results

Process Flow:
1. Load test dataset with questions and expected responses
2. Generate actual responses using search system
3. Evaluate response quality using GPT-4
4. Score responses on 0-100 scale
5. Provide detailed reasoning for scores
6. Save evaluation results to CSV file

Author: Sai
"""

import pandas as pd

import openai
from key import OPENAI_API_KEY
from search import ask_query

openai_client = openai.OpenAI(api_key=OPENAI_API_KEY)

import json

def evaluate_response_llm(question, expected_response, actual_response):
    prompt = f"""
    You are an expert in healthcare regulation compliance. A user asked a question, and two responses are provided:
    - Expected Response provided by the client: {expected_response}
    - Actual Response generated by the bot: {actual_response}
    
    Evaluate how well the actual response answers the question in terms of
    1. If all the contents present in the Expected Response provided by the client present in the Actual Response generated by the bot.
    
    Question: {question}
    
    Respond in JSON format:
    {{
      "score": <0-100 scale>,
      "reason": "<mention what details are missing if any, else mention NA>"
    }}
    """

    response = openai_client.chat.completions.create(
        model="gpt-4",
        messages=[{"role": "user", "content": prompt}],
        temperature=0
    )

    content = response.choices[0].message.content
    try:
        json_data = json.loads(content)
        return json_data["score"], json_data["reason"]
    except Exception as e:
        print(f"[ERROR] Failed to parse LLM response: {content}\nError: {e}")
        return None, "Invalid response format"

test_set = pd.read_csv("data/testset_q_a.csv")
evaluation_df = {'question':[], 'expected_response':[], 'actual_response':[], 'score':[], 'reason':[]}
for i, row in test_set.iterrows():
    question = row['question']
    expected_response = row['expected_response']
    actual_response, chunks = ask_query(question)
    score, reason = evaluate_response_llm(question, expected_response, actual_response)
    evaluation_df['question'].append(question)
    evaluation_df['expected_response'].append(expected_response)
    evaluation_df['actual_response'].append(actual_response)
    evaluation_df['score'].append(score)
    evaluation_df['reason'].append(reason)
    #evaluation_df['chunks'].append(chunks)

pd.DataFrame(evaluation_df).to_csv("data/evaluation.csv", index=False)



